// Writes the Supabase Auth email templates in supabase/email-templates/ from
// the same layout the app's own email uses, so the two can't drift apart.
// Supabase keeps its templates in the dashboard, not the repo: after running
// this, paste the changed files there (see supabase/email-templates/README.md).
//
//   node scripts/build-auth-email-templates.mjs

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { renderEmailLayout } from "../src/utils/email.js";

const outDir = fileURLToPath(new URL("../supabase/email-templates/", import.meta.url));

// Left as Supabase's literal template variable: Supabase substitutes it when
// it sends, and it must never pass through escapeHtml.
const CONFIRMATION_URL = "{{ .ConfirmationURL }}";

// Some clients strip or break buttons, so the link is also printed in full.
const fallback = `If the button doesn't work, paste this link into your browser:<br><a href="${CONFIRMATION_URL}" style="color:#123f38;word-break:break-all;">${CONFIRMATION_URL}</a>`;

const templates = {
  "confirm-signup": {
    dashboardName: "Confirm signup",
    heading: "Confirm your email",
    paragraphs: ["Welcome to FirstFinder. Confirm this address and your account is ready to start a collection."],
    button: { href: CONFIRMATION_URL, label: "Confirm my email" },
    footer: `${fallback}<br><br>If you didn't sign up for FirstFinder, you can ignore this email and no account will be created.`
  },
  "reset-password": {
    dashboardName: "Reset password",
    heading: "Reset your password",
    paragraphs: ["Someone asked to reset the password for your FirstFinder account. If that was you, choose a new one here."],
    button: { href: CONFIRMATION_URL, label: "Choose a new password" },
    footer: `${fallback}<br><br>If you didn't ask for this, ignore this email. Your password stays the same.`
  },
  "magic-link": {
    dashboardName: "Magic link",
    heading: "Your sign-in link",
    paragraphs: ["Here's your link to sign in to FirstFinder. It works once and expires soon."],
    button: { href: CONFIRMATION_URL, label: "Sign in to FirstFinder" },
    footer: `${fallback}<br><br>If you didn't ask to sign in, ignore this email. Nobody can get in without this link.`
  },
  "change-email": {
    dashboardName: "Change email address",
    heading: "Confirm your new email",
    paragraphs: ["You asked to change the email on your FirstFinder account from {{ .Email }} to {{ .NewEmail }}. Confirm the change here."],
    button: { href: CONFIRMATION_URL, label: "Confirm the change" },
    footer: `${fallback}<br><br>If you didn't ask for this, ignore this email and nothing changes.`
  }
};

for (const [name, { dashboardName, ...args }] of Object.entries(templates)) {
  const header = `<!-- Supabase Auth template: paste into Authentication -> Email Templates -> ${dashboardName}. Generated by scripts/build-auth-email-templates.mjs; edit that, not this. Keep {{ .ConfirmationURL }} intact. See supabase/email-templates/README.md. -->\n`;
  writeFileSync(`${outDir}${name}.html`, header + renderEmailLayout(args) + "\n");
  console.log(`wrote supabase/email-templates/${name}.html`);
}
